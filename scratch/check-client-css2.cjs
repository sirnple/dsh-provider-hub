const fs = require('node:fs')
const source = fs.readFileSync('C:/Users/Administrator/repos/dsh-provider-accounts/plugin/client.js', 'utf8')
const start = source.indexOf('const CSS = `')
const end = source.indexOf('`', start + 14)
const css = source.slice(start, end)
const hex = [...css.matchAll(/#[0-9a-fA-F]{3,8}/g)].map((match) => match[0])
const functional = [...css.matchAll(/\b(?:rgba?|hsla?)\(/g)].map((match) => match[0])
const named = [...css.matchAll(/:\s*(red|green|blue|black|white|gray|grey|orange)\b/g)].map((match) => match[0])
const tokens = new Set([...css.matchAll(/var\((--dsw-[a-z0-9-]+)/g)].map((match) => match[1]))
const unknownTokens = [...tokens].filter((token) => !/^--dsw-(alias|elevation|focus|font|radius|mask|specific|static|shadow)/.test(token))
console.log('hex colors:', hex)
